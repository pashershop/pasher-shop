// Flat searchable list of all divisions, districts and upazilas
export interface LocationSearchResult {
  id: string;
  nameBn: string;
  type: 'division' | 'district' | 'upazila';
  typeLabelBn: string;
  parentNameBn?: string;
  lat: number;
  lng: number;
}

export const getAllSearchableLocations = (): LocationSearchResult[] => {
  const results: LocationSearchResult[] = [];

  BANGLADESH_DIVISIONS.forEach((div) => {
    // Division entry
    results.push({
      id: `div-${div.id}`,
      nameBn: div.nameBn,
      type: 'division',
      typeLabelBn: 'বিভাগ',
      lat: div.lat,
      lng: div.lng,
    });

    div.districts.forEach((dist) => {
      // District entry
      results.push({
        id: `dist-${dist.id}`,
        nameBn: `${dist.nameBn}, ${div.nameBn}`,
        type: 'district',
        typeLabelBn: 'জেলা',
        parentNameBn: div.nameBn,
        lat: dist.lat,
        lng: dist.lng,
      });

      // Upazila entries
      dist.upazilas.forEach((upazila, uIdx) => {
        results.push({
          id: `upz-${dist.id}-${uIdx}`,
          nameBn: `${upazila}, ${dist.nameBn}`,
          type: 'upazila',
          typeLabelBn: 'উপজেলা/থানা',
          parentNameBn: `${dist.nameBn}, ${div.nameBn}`,
          lat: dist.lat,
          lng: dist.lng,
        });
      });
    });
  });

  return results;
};
